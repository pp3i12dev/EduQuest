import { Router } from 'express';
import { authenticate, requirePermission } from '../middlewares/auth.middleware.js';
import { list, create, addTopic, changeTopic } from '../controllers/unit.controller.js';
const router = Router();
router.use(authenticate, requirePermission('subjectContent:manage'));
router.get('/', list);
router.post('/', create);
router.post('/:unitId/topics', addTopic);
router.put('/:unitId/topics/:topicId', changeTopic);
export default router;
